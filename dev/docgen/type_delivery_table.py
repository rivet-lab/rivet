#!/usr/bin/env python3
"""Generate docs/type-delivery-table.md from docs/type-capability-matrix.yaml (read-only view of the ledger)."""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
LEDGER = ROOT / "docs" / "type-capability-matrix.yaml"
LEGS = ("clickhouse", "bigquery", "snowflake")
HEAD = ("engine", "native type", "batch", "CDC", "ClickHouse", "BigQuery", "Snowflake")
GAP = "**GAP**"


def esc(text: str) -> str:
    """A table cell: pipes escaped, no newline."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def cell(value, today=None, marked=False) -> str:
    """One delivered type; a marked row shows what ships today beside the declared target."""
    if not value:
        return GAP
    out = f"`{esc(value)}`"
    return f"{out}; today `{esc(today)}` (defect)" if marked and today else out


def row_cells(engine: str, r: dict) -> list[str]:
    """The seven cells of one delivering row."""
    kd = bool(r.get("known_defect"))
    batch = cell(r.get("delivery"), r.get("today_delivery"), kd)
    cdc = f"`{esc(r['cdc'])}`" if r.get("cdc") else GAP
    legs = []
    for leg in LEGS:
        m = r.get(leg) or {}
        legs.append(cell(m.get("type"), m.get("today"), kd or bool(m.get("defect"))))
    return [engine, f"`{esc(r['native_type'])}`", batch, cdc, *legs]


def recover_section(doc: dict) -> list[str]:
    """The BigQuery expressions that turn an INT64 nanosecond column back into a native value."""
    out = ["## Recovering a value that lands as INT64 nanoseconds on BigQuery", ""]
    for name, r in doc["native_recover"].items():
        rows = ", ".join(f"`{esc(x)}`" for x in r["rows"])
        out += [f"Rows: {rows}. `x` is the INT64 column.", "", "| result | expression |", "| --- | --- |"]
        out += [f"| {k.replace('_', ' ')} | `{esc(v)}` |" for k, v in r.items() if k != "rows"]
        out.append("")
    return out


def render(doc: dict) -> str:
    """The whole document."""
    body, summary, gaps = [], [], []
    for engine, e in doc["engines"].items():
        rows = e.get("rows") or []
        delivering = [r for r in rows if r.get("delivery")]
        matrix_only = [r for r in rows if not r.get("delivery")]
        n_gap = 0
        for r in delivering:
            cells = row_cells(engine, r)
            n_gap += sum(c == GAP for c in cells)
            body.append(cells)
            gaps += [f"- {engine} `{r['native_type']}`: {h} is empty" for h, c in zip(HEAD, cells) if c == GAP]
        with_na = [r for r in matrix_only if r.get("na")]
        for r in with_na:
            body.append([engine, f"`{esc(r['native_type'])}`", esc(r["na"]), "n/a", "n/a", "n/a", "n/a"])
        rest = [r for r in matrix_only if not r.get("na")]
        if rest:
            names = ", ".join(f"`{esc(r['native_type'])}`" for r in rest)
            note = "n/a: no `delivery`, graded by the edge matrix only (a refused or text-only column)"
            body.append([engine, f"{len(rest)} matrix-only rows: {names}", note, "n/a", "n/a", "n/a", "n/a"])
        marked = sum(bool(r.get("known_defect") or any((r.get(g) or {}).get("defect") for g in LEGS)) for r in delivering)
        summary.append((engine, len(delivering), len(matrix_only), marked, n_gap))
    out = [
        "<!-- GENERATED by dev/docgen/type_delivery_table.py from docs/type-capability-matrix.yaml — DO NOT EDIT BY HAND. -->",
        "",
        "# Type delivery table",
        "",
        "One row per delivering ledger row: the source native type, the Arrow type batch writes, the change-stream verdict, and the column type `rivet load` builds in ClickHouse, BigQuery and Snowflake. `today` marks a row that ships a type other than its target (`known_defect` or a leg `defect`).",
        "",
        "## Gaps per engine",
        "",
        "| engine | delivering rows | matrix-only rows | rows with a defect | empty cells |",
        "| --- | --- | --- | --- | --- |",
        *[f"| {a} | {b} | {c} | {d} | {g} |" for a, b, c, d, g in summary],
        "",
        *(["## Empty cells", "", *gaps, ""] if gaps else ["No cell is empty.", ""]),
        "## Table",
        "",
        "| " + " | ".join(HEAD) + " |",
        "| " + " | ".join("---" for _ in HEAD) + " |",
        *["| " + " | ".join(c) + " |" for c in body],
        "",
        *recover_section(doc),
    ]
    return "\n".join(out)


def main() -> int:
    """Write the document to stdout."""
    sys.stdout.write(render(yaml.safe_load(LEDGER.read_text())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
